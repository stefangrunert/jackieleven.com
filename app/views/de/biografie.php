  <h1>Die Autobiografie, die er nie geschrieben hat</h1>

  <aside class="pastiche-hinweis" role="note">
    <span class="etikett">Pastiche</span>
    <p><strong>Dieser Text ist nicht von Jackie Leven.</strong> Wir haben ihn geschrieben, in seiner
    Stimme, auf Grundlage dessen, was er selbst über sich erzählt hat. Seine eigenen Worte stehen in
    der <a href="<?= e(url('start')) ?>">Zeitreise</a>, jedes mit Quelle.</p>
  </aside>

  <p class="lead">Leven hat nie eine Autobiografie geschrieben. Er hat aber neun Jahre lang auf
  seinen Websites über sein Leben erzählt, in einer Stimme, die man wiedererkennt: kleines „i“,
  lange Sätze, Gedankenstriche statt Punkte, Witze auf eigene Kosten. Aus diesen Texten ist die
  Pastiche entstanden, fünfzehn Kapitel in der Reihenfolge, in der er sein Leben gelebt hat, nicht in
  der, in der er davon erzählte.</p>

  <p>Leven hat seine Geschichte gern ausgeschmückt, und schon seine echten Erinnerungen klingen oft
  wie Erfindungen. Damit sich später noch trennen lässt, was von ihm stammt und was von uns, endet
  jedes Kapitel mit einer Aufstellung, was belegt ist und was wir erfunden haben. Wo er selbst
  geflunkert hat, bei Bob Dylan, dem Whisky oder der Auftragsmörderin, erzählt das Buch es als
  seine Geschichte.</p>

  <p>Die Kapitel sind im Original englisch geschrieben; hier steht unsere deutsche Fassung, das
  Original unter <a href="<?= e(url('biografie', [], 'en')) ?>" hreflang="en" lang="en">English</a>.
  Sein kleines „i“ haben wir als kleines „ich“ übernommen, auch am Satzanfang. Ab Kapitel 14, wo
  er selbst zum großen „I“ wechselt, steht es groß.</p>

