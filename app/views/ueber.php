  <h1>Eine private Hommage</h1>

  <p class="lead">Diese Seite ist von Hand gebaut, gehört niemandem außer ihrem Verfasser und vertritt
  weder Jackie Levens Nachlass noch eine Plattenfirma. Sie ist entstanden, weil seine Musik
  jemandem etwas bedeutet hat.</p>

  <h2>Woher das Material stammt</h2>
  <p>Jackie Leven hat zwischen Oktober 2002 und Herbst 2011 auf seinen eigenen Websites
  geschrieben: erst die Monatskolumne <em>The Deep Pool</em> auf jackieleven.com, ab 2008 einen Blog
  und mehrere Rubriken auf jackieleven.co.uk. Beide Seiten sind seit Jahren offline. Über das
  Internet Archive ließen sich 76 dieser Texte wiederherstellen, rund 90.000 Wörter.</p>
  <p>Jedes Zitat auf dieser Seite stammt wortgetreu aus diesen Texten und ist mit Datum und
  Archivlink belegt. Nichts davon ist übersetzt, nachgedichtet oder sinngemäß wiedergegeben.
  Die deutschen Begleittexte sind erkennbar unsere und stehen nie in Anführungszeichen.</p>

  <h2>Was hier nicht steht</h2>
  <p>Keine Songtexte. Die Rechte daran liegen nicht bei uns, und eine Hommage, die sich am
  Urheberrecht des Geehrten vergreift, wäre eine merkwürdige Hommage.</p>
  <p>Keine erfundenen Zitate. Leven war ein notorischer Geschichtenerzähler — Bob Dylan als
  angeblicher Ko-Autor, ein eigener Whisky, eine Auftragsmörderin als Inspiration. Seine echten
  Erinnerungen klingen bereits wie Erfindungen. Wer dem noch erfundene Sätze hinzufügt und sie
  ihm zuschreibt, macht seine Biografie endgültig unlesbar.</p>
  <p>Und da, wo er geschwiegen hat, steht nichts. Über den Überfall, der ihn beinahe die Stimme
  gekostet hat, hat er in neun Jahren öffentlichen Schreibens kein einziges Mal etwas gesagt.
  Diese Leerstelle bleibt eine.</p>

  <h2>Widersprüche</h2>
  <p>Die Recherche hat mehr Unstimmigkeiten ergeben, als eine Zeitleiste vertragen kann: zwei
  Geburtsdaten, zwei Gründungsjahre der Band, zwei Jahre für den Überfall, drei Angaben zur
  Krebsart. Wo die Quellen sich widersprechen, folgt diese Seite Levens eigener Version und sagt
  es dazu.</p>
